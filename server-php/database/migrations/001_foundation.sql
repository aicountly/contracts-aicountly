-- Contracts foundation: the contract record itself, its taxonomy, its parties,
-- and the per-company configuration those depend on.
--
-- Conventions used throughout this schema:
--   * BIGINT identity primary keys, plus a UUID for anything a URL or another
--     product may reference — sequential ids in a URL are an enumeration hint.
--   * (environment, cmp_id) on every tenant-owned table. environment looks
--     redundant while each deployment has its own database, and stops being
--     redundant the first time a production dump is restored into sandbox.
--   * Bare TIMESTAMP columns holding UTC. The connection pins `SET TIME ZONE
--     'UTC'` (App\Core\Database), so every stored instant means one thing.
--   * JSONB only for genuinely open-ended metadata. Anything filtered,
--     summed or sorted gets a real column.

-- ---------------------------------------------------------------------------
-- Per-company Contracts settings
-- ---------------------------------------------------------------------------
CREATE TABLE contract_settings (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment           VARCHAR(16)  NOT NULL,
    cmp_id                BIGINT       NOT NULL,

    number_prefix         VARCHAR(16)  NOT NULL DEFAULT 'CON',
    number_pad            SMALLINT     NOT NULL DEFAULT 6,
    number_include_year   BOOLEAN      NOT NULL DEFAULT TRUE,
    number_reset_yearly   BOOLEAN      NOT NULL DEFAULT TRUE,

    default_currency      VARCHAR(3)   NOT NULL DEFAULT 'INR',
    default_notice_days   SMALLINT     NOT NULL DEFAULT 30,
    expiry_alert_days     VARCHAR(64)  NOT NULL DEFAULT '90,60,30,15,7',
    obligation_alert_days VARCHAR(64)  NOT NULL DEFAULT '14,7,1',
    approval_escalation_days SMALLINT  NOT NULL DEFAULT 3,

    ai_enabled            BOOLEAN      NOT NULL DEFAULT TRUE,
    ai_auto_extract       BOOLEAN      NOT NULL DEFAULT TRUE,
    ai_auto_risk          BOOLEAN      NOT NULL DEFAULT TRUE,

    -- Which role a company member gets when nobody has granted them one.
    -- Mirrors Drive's DOCS_COMPANY_DEFAULT_ACCESS idea: a company that has not
    -- configured Contracts should still be usable, without that meaning
    -- everyone can approve their own contracts.
    default_role          VARCHAR(32)  NOT NULL DEFAULT 'read_only',

    settings_json         JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_contract_settings_tenant UNIQUE (environment, cmp_id),
    CONSTRAINT ck_contract_settings_pad CHECK (number_pad BETWEEN 3 AND 12)
);

-- ---------------------------------------------------------------------------
-- Contract types — configurable, never hard-coded in business logic
-- ---------------------------------------------------------------------------
CREATE TABLE contract_types (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                UUID         NOT NULL DEFAULT gen_random_uuid(),
    environment         VARCHAR(16)  NOT NULL,
    -- cmp_id 0 marks a system seed every company inherits until it customises
    -- one. Cloning on first edit keeps one company's rename from moving another
    -- company's contracts to a different type.
    cmp_id              BIGINT       NOT NULL,
    code                VARCHAR(64)  NOT NULL,
    name                VARCHAR(160) NOT NULL,
    description         TEXT         NULL,
    category            VARCHAR(64)  NOT NULL DEFAULT 'general',
    counterparty_side   VARCHAR(16)  NOT NULL DEFAULT 'either',

    default_renewal_type    VARCHAR(24) NULL,
    default_notice_days     SMALLINT    NULL,
    default_term_months     SMALLINT    NULL,

    required_fields     JSONB        NOT NULL DEFAULT '[]'::jsonb,
    mandatory_clauses   JSONB        NOT NULL DEFAULT '[]'::jsonb,
    default_template_id BIGINT       NULL,
    approval_workflow_id BIGINT      NULL,

    is_system           BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active           BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order          INTEGER      NOT NULL DEFAULT 100,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_contract_types_code UNIQUE (environment, cmp_id, code),
    CONSTRAINT ck_contract_types_side CHECK (counterparty_side IN ('customer', 'vendor', 'internal', 'either'))
);

CREATE INDEX idx_contract_types_tenant ON contract_types (environment, cmp_id, is_active);

-- ---------------------------------------------------------------------------
-- Departments (Contracts-owned; Manage does not model these)
-- ---------------------------------------------------------------------------
CREATE TABLE contract_departments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment  VARCHAR(16)  NOT NULL,
    cmp_id       BIGINT       NOT NULL,
    name         VARCHAR(120) NOT NULL,
    code         VARCHAR(48)  NOT NULL,
    head_uuid    VARCHAR(64)  NULL,
    is_active    BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_contract_departments_code UNIQUE (environment, cmp_id, code)
);

-- ---------------------------------------------------------------------------
-- Role grants — Contracts' own RBAC
-- ---------------------------------------------------------------------------
CREATE TABLE contract_user_roles (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment  VARCHAR(16)  NOT NULL,
    cmp_id       BIGINT       NOT NULL,
    user_uuid    VARCHAR(64)  NOT NULL,
    role_slug    VARCHAR(32)  NOT NULL,
    department_id BIGINT      NULL REFERENCES contract_departments (id) ON DELETE SET NULL,
    granted_by   VARCHAR(64)  NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_contract_user_roles UNIQUE (environment, cmp_id, user_uuid, role_slug)
);

CREATE INDEX idx_contract_user_roles_lookup ON contract_user_roles (environment, cmp_id, user_uuid);

-- ---------------------------------------------------------------------------
-- Tags
-- ---------------------------------------------------------------------------
CREATE TABLE contract_tags (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment VARCHAR(16)  NOT NULL,
    cmp_id      BIGINT       NOT NULL,
    name        VARCHAR(64)  NOT NULL,
    colour      VARCHAR(16)  NOT NULL DEFAULT 'slate',
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_contract_tags_name UNIQUE (environment, cmp_id, name)
